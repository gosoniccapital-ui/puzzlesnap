export function getDailyPuzzle(): PuzzleItem {
  // Rotate through the 236 high-definition Space Odyssey collection based on calendar day
  const spacePuzzles = PUZZLES_DATA.filter((p) => p.categorySlug === "space");
  const pool = spacePuzzles.length > 0 ? spacePuzzles : PUZZLES_DATA;
  const dayNumber = Math.floor(Date.now() / 86400000);
  const index = Math.abs(dayNumber) % pool.length;
  const puzzle = pool[index] || pool[0];
  return {
    ...puzzle,
    isDaily: true,
  };
}

export function getPuzzleBySlug(slug: string): PuzzleItem | undefined {
  if (slug === "daily") {
    return getDailyPuzzle();
  }
  return PUZZLES_DATA.find((p) => p.slug === slug);
}

export function getPuzzlesByCategory(categorySlug: string): PuzzleItem[] {
  return PUZZLES_DATA.filter((p) => p.categorySlug === categorySlug);
}

export function searchPuzzles(query: string): PuzzleItem[] {
  const q = query.toLowerCase().trim();
  if (!q) return PUZZLES_DATA;
  return PUZZLES_DATA.filter(
    (p) =>
      p.title.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q)
  );
}

export function addPuzzleItem(item: Omit<PuzzleItem, "id" | "plays" | "likes">): PuzzleItem {
  const newItem: PuzzleItem = {
    ...item,
    id: "p" + (PUZZLES_DATA.length + 1) + "-" + Date.now().toString(36),
    plays: 0,
    likes: 0,
  };
  PUZZLES_DATA.unshift(newItem);
  return newItem;
}

export function deletePuzzleItem(id: string): boolean {
  const index = PUZZLES_DATA.findIndex((p) => p.id === id);
  if (index !== -1) {
    PUZZLES_DATA.splice(index, 1);
    return true;
  }
  return false;
}

export function updatePuzzleItem(
  id: string,
  updates: Partial<Omit<PuzzleItem, "id">>
): PuzzleItem | null {
  const index = PUZZLES_DATA.findIndex((p) => p.id === id);
  if (index === -1) return null;

  PUZZLES_DATA[index] = {
    ...PUZZLES_DATA[index],
    ...updates,
  };
  return PUZZLES_DATA[index];
}

export function incrementLikes(slug: string): number | null {
  const puzzle = PUZZLES_DATA.find((p) => p.slug === slug);
  if (!puzzle) return null;
  puzzle.likes = (puzzle.likes || 0) + 1;
  return puzzle.likes;
}

export function incrementPlays(slug: string): number | null {
  const puzzle = PUZZLES_DATA.find((p) => p.slug === slug);
  if (!puzzle) return null;
  puzzle.plays = (puzzle.plays || 0) + 1;
  return puzzle.plays;
}
